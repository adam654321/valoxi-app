import { Router, Request, Response } from 'express';
import { eq } from 'drizzle-orm';
import { asyncHandler } from '../utils/async-handler';
import { sendSuccess } from '../utils/response';
import { NotFoundError, BadRequestError } from '../utils/errors';
import { db } from '../db';
import { users, waitlist, marketingConsentTokens } from '@shared/schema';
import { marketingConsentTokenRepository } from '../repositories/marketing-consent-token.repository';
import { marketingContactsService } from '../services/marketing-contacts.service';

const router = Router();

// Strict token shape: 64-char hex generated by randomBytes(32).toString('hex')
function isValidTokenShape(token: string): boolean {
  return /^[a-f0-9]{64}$/.test(token);
}

function extractIp(req: Request): string | null {
  const ip = req.ip || (req.headers['x-forwarded-for'] as string | undefined)?.split(',')[0]?.trim() || null;
  return ip;
}

/**
 * GET /api/v2/public/marketing-consent/:token
 * Read-only validity check called by the client page on mount.
 * Returns the recipient email + state so the page can render appropriately.
 */
router.get('/:token', asyncHandler(async (req: Request, res: Response) => {
  const { token } = req.params;

  if (!isValidTokenShape(token)) {
    throw new NotFoundError('Token not found');
  }

  const row = await marketingConsentTokenRepository.getByToken(token);
  if (!row) {
    throw new NotFoundError('Token not found');
  }

  const now = new Date();
  if (row.expiresAt < now && !row.consentRecordedAt) {
    throw new BadRequestError('Token has expired');
  }

  return sendSuccess(res, {
    email: row.email,
    alreadyConsented: row.consentRecordedAt !== null,
    consentRecordedAt: row.consentRecordedAt,
  });
}));

/**
 * POST /api/v2/public/marketing-consent/:token/confirm
 * Records consent. Idempotent: clicking twice is treated as success and does
 * NOT re-trigger Resend sync or overwrite the original consentRecordedAt.
 */
router.post('/:token/confirm', asyncHandler(async (req: Request, res: Response) => {
  const { token } = req.params;

  if (!isValidTokenShape(token)) {
    throw new NotFoundError('Token not found');
  }

  const tokenRow = await marketingConsentTokenRepository.getByToken(token);
  if (!tokenRow) {
    throw new NotFoundError('Token not found');
  }

  // Idempotent: already consented = return success, no side effects.
  if (tokenRow.consentRecordedAt) {
    return sendSuccess(res, {
      email: tokenRow.email,
      alreadyConsented: true,
      consentRecordedAt: tokenRow.consentRecordedAt,
    });
  }

  // Expired AND not yet consented = rejected.
  const now = new Date();
  if (tokenRow.expiresAt < now) {
    throw new BadRequestError('Token has expired');
  }

  const ip = extractIp(req);
  const consentTime = new Date();

  await db.transaction(async (tx) => {
    if (tokenRow.userId !== null) {
      await tx
        .update(users)
        .set({ marketingConsent: true, marketingConsentAt: consentTime })
        .where(eq(users.id, tokenRow.userId));
    } else if (tokenRow.waitlistId !== null) {
      await tx
        .update(waitlist)
        .set({ marketingConsent: true, marketingConsentAt: consentTime })
        .where(eq(waitlist.id, tokenRow.waitlistId));
    }

    await tx
      .update(marketingConsentTokens)
      .set({ consentRecordedAt: consentTime, ipAddress: ip })
      .where(eq(marketingConsentTokens.id, tokenRow.id));
  });

  // Fire-and-forget Resend sync for user-targeted consent.
  // Waitlist consent syncs at invite time (177.1A-S2 already handles this).
  if (tokenRow.userId !== null) {
    void marketingContactsService.upsertContact(tokenRow.userId);
  }

  return sendSuccess(res, {
    email: tokenRow.email,
    alreadyConsented: false,
    consentRecordedAt: consentTime.toISOString(),
  });
}));

export default router;
