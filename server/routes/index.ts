import { Express } from 'express';
import pipelineRoutes from './pipeline.routes';
import rolesRoutes from './roles.routes';
import contactsRoutes from './contacts.routes';
import activitiesRoutes from './activities.routes';
import notificationsRoutes from './notifications.routes';
import documentsRoutes from './documents.routes';
import targetCompaniesRoutes from './target-companies.routes';
import authRoutes from './auth.routes';
import notesRoutes from './notes.routes';
import dashboardRoutes from './dashboard.routes';
import teamRoutes, { publicTeamRoutes } from './team.routes';
import assignmentsRoutes from './assignments.routes';
import reportsRoutes from './reports.routes';
import portalRoutes, { portalPublicRoutes } from './portal.routes';
import documentsFilesRoutes, { publicDocumentRoutes } from './documents-files.routes';
import portalSubmissionsRoutes from './portal-submissions.routes';
import documentAnalysisRoutes from './document-analysis.routes';
import portalRequirementsRoutes, { portalRequirementsPublicRoutes } from './portal-requirements.routes';
import emailRoutes from './email.routes';
import websiteAnalysisRoutes from './website-analysis.routes';
import financialDataRoutes from './financial-data.routes';
import chaseUpRoutes from './chase-up.routes';
import expertAnalysisRoutes from './expert-analysis.routes';
import userCompaniesRoutes from './user-companies.routes';
import dealModelRoutes from './deal-model.routes';
import dealDocumentRoutes, { publicDealDocumentRoutes } from './deal-document.routes';
import dueDiligenceRoutes from './due-diligence.routes';
import valueCreationRoutes from './value-creation.routes';
import adminRoutes from './admin.routes';
import { isAuthenticated, isSystemAdmin, requirePermission } from '../middleware/auth';
import { validateCsrfToken } from '../middleware/csrf';
import { portalLimiter, analysisTriggerLimiter } from '../middleware/rate-limit';

export function registerModularRoutes(app: Express) {
  app.use('/api/v2/pipeline', isAuthenticated, validateCsrfToken, pipelineRoutes);
  app.use('/api/v2/roles', isAuthenticated, validateCsrfToken, rolesRoutes);
  app.use('/api/v2/contacts', isAuthenticated, validateCsrfToken, contactsRoutes);
  app.use('/api/v2/activities', isAuthenticated, validateCsrfToken, activitiesRoutes);
  app.use('/api/v2/notifications', isAuthenticated, validateCsrfToken, notificationsRoutes);
  app.use('/api/v2/documents', isAuthenticated, validateCsrfToken, documentsRoutes);
  app.use('/api/v2/target-companies', isAuthenticated, validateCsrfToken, targetCompaniesRoutes);
  app.use('/api/v2/auth', authRoutes);
  app.use('/api/v2/notes', isAuthenticated, validateCsrfToken, notesRoutes);
  app.use('/api/v2/dashboard', isAuthenticated, validateCsrfToken, dashboardRoutes);
  app.use('/api/v2/team', publicTeamRoutes);
  app.use('/api/v2/team', isAuthenticated, validateCsrfToken, requirePermission('canManageUsers'), teamRoutes);
  app.use('/api/v2/deals', isAuthenticated, validateCsrfToken, assignmentsRoutes);
  app.use('/api/v2/reports', isAuthenticated, validateCsrfToken, requirePermission('canAccessAnalytics'), reportsRoutes);
  app.use('/api/v2/portal', portalLimiter, portalPublicRoutes);
  app.use('/api/v2/portal', isAuthenticated, validateCsrfToken, portalRoutes);
  app.use('/api/v2/files', isAuthenticated, validateCsrfToken, documentsFilesRoutes);
  app.use('/api/v2/public/documents', publicDocumentRoutes);
  app.use('/api/v2/portal-submit', portalLimiter, portalSubmissionsRoutes);
  app.use('/api/v2/document-analysis', isAuthenticated, validateCsrfToken, documentAnalysisRoutes);
  app.use('/api/v2/requirements', isAuthenticated, validateCsrfToken, portalRequirementsRoutes);
  app.use('/api/v2/public/portal', portalLimiter, portalRequirementsPublicRoutes);
  app.use('/api/v2/email', isAuthenticated, validateCsrfToken, emailRoutes);
  app.use('/api/v2/website-analysis', isAuthenticated, validateCsrfToken, analysisTriggerLimiter, websiteAnalysisRoutes);
  app.use('/api/v2/financial-data', isAuthenticated, validateCsrfToken, requirePermission('canViewFinancials'), financialDataRoutes);
  app.use('/api/v2/chase-up', isAuthenticated, validateCsrfToken, chaseUpRoutes);
  app.use('/api/v2/expert-analysis', isAuthenticated, validateCsrfToken, requirePermission('canViewFinancials'), analysisTriggerLimiter, expertAnalysisRoutes);
  app.use('/api/v2/user/companies', isAuthenticated, validateCsrfToken, userCompaniesRoutes);
  app.use('/api/v2/deal-models', isAuthenticated, validateCsrfToken, dealModelRoutes);
  app.use('/api/v2/deal-documents', isAuthenticated, validateCsrfToken, dealDocumentRoutes);
  app.use('/api/v2/public/deal-documents', portalLimiter, publicDealDocumentRoutes);
  app.use('/api/v2/due-diligence', isAuthenticated, validateCsrfToken, dueDiligenceRoutes);
  app.use('/api/v2/value-creation', isAuthenticated, validateCsrfToken, valueCreationRoutes);
  app.use('/api/v2/admin', isAuthenticated, validateCsrfToken, isSystemAdmin, adminRoutes);
}
