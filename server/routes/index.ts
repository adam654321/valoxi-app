import { Express } from 'express';
import pipelineRoutes from './pipeline.routes';
import rolesRoutes from './roles.routes';
import contactsRoutes from './contacts.routes';
import activitiesRoutes from './activities.routes';
import notificationsRoutes from './notifications.routes';
import documentsRoutes from './documents.routes';
import targetCompaniesRoutes from './target-companies.routes';
import authRoutes from './auth.routes';
import notesRoutes from './notes.routes';
import dashboardRoutes from './dashboard.routes';
import teamRoutes, { publicTeamRoutes } from './team.routes';
import assignmentsRoutes from './assignments.routes';
import reportsRoutes from './reports.routes';
import portalRoutes from './portal.routes';
import documentsFilesRoutes, { publicDocumentRoutes } from './documents-files.routes';
import portalSubmissionsRoutes from './portal-submissions.routes';
import documentAnalysisRoutes from './document-analysis.routes';
import portalRequirementsRoutes, { portalRequirementsPublicRoutes } from './portal-requirements.routes';
import emailRoutes from './email.routes';
import websiteAnalysisRoutes from './website-analysis.routes';
import debugRoutes from './debug.routes';
import financialDataRoutes from './financial-data.routes';
import chaseUpRoutes from './chase-up.routes';
import expertAnalysisRoutes from './expert-analysis.routes';
import userCompaniesRoutes from './user-companies.routes';
import dealModelRoutes from './deal-model.routes';
import dealDocumentRoutes, { publicDealDocumentRoutes } from './deal-document.routes';
import dueDiligenceRoutes from './due-diligence.routes';
import valueCreationRoutes from './value-creation.routes';
import { authLimiter, portalLimiter, analysisTriggerLimiter } from '../middleware/rate-limit';

export function registerModularRoutes(app: Express, isAuthenticated: any) {
  app.use('/api/v2/pipeline', isAuthenticated, pipelineRoutes);
  app.use('/api/v2/roles', isAuthenticated, rolesRoutes);
  app.use('/api/v2/contacts', isAuthenticated, contactsRoutes);
  app.use('/api/v2/activities', isAuthenticated, activitiesRoutes);
  app.use('/api/v2/notifications', isAuthenticated, notificationsRoutes);
  app.use('/api/v2/documents', isAuthenticated, documentsRoutes);
  app.use('/api/v2/target-companies', isAuthenticated, targetCompaniesRoutes);
  app.use('/api/v2/auth', authLimiter, authRoutes);
  app.use('/api/v2/notes', isAuthenticated, notesRoutes);
  app.use('/api/v2/dashboard', isAuthenticated, dashboardRoutes);
  app.use('/api/v2/team', publicTeamRoutes);
  app.use('/api/v2/team', isAuthenticated, teamRoutes);
  app.use('/api/v2/deals', isAuthenticated, assignmentsRoutes);
  app.use('/api/v2/reports', isAuthenticated, reportsRoutes);
  app.use('/api/v2/portal', portalLimiter, portalRoutes);
  app.use('/api/v2/files', isAuthenticated, documentsFilesRoutes);
  app.use('/api/v2/public/documents', publicDocumentRoutes);
  app.use('/api/v2/portal-submit', portalLimiter, portalSubmissionsRoutes);
  app.use('/api/v2/document-analysis', isAuthenticated, documentAnalysisRoutes);
  app.use('/api/v2/requirements', isAuthenticated, portalRequirementsRoutes);
  app.use('/api/v2/public/portal', portalLimiter, portalRequirementsPublicRoutes);
  app.use('/api/v2/email', isAuthenticated, emailRoutes);
  app.use('/api/v2/website-analysis', isAuthenticated, analysisTriggerLimiter, websiteAnalysisRoutes);
  if (process.env.NODE_ENV !== 'production') {
    app.use('/api/v2/debug', isAuthenticated, debugRoutes);
  }
  app.use('/api/v2/financial-data', isAuthenticated, financialDataRoutes);
  app.use('/api/v2/chase-up', isAuthenticated, chaseUpRoutes);
  app.use('/api/v2/expert-analysis', isAuthenticated, analysisTriggerLimiter, expertAnalysisRoutes);
  app.use('/api/v2/user/companies', isAuthenticated, userCompaniesRoutes);
  app.use('/api/v2/deal-models', isAuthenticated, dealModelRoutes);
  app.use('/api/v2/deal-documents', isAuthenticated, dealDocumentRoutes);
  app.use('/api/v2/public/deal-documents', portalLimiter, publicDealDocumentRoutes);
  app.use('/api/v2/due-diligence', isAuthenticated, dueDiligenceRoutes);
  app.use('/api/v2/value-creation', isAuthenticated, valueCreationRoutes);
}
