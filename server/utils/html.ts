/**
 * Escapes special HTML characters in a string to prevent HTML injection.
 * Use this on all user-supplied values before interpolating into HTML strings.
 */
export function escapeHtml(value: string | null | undefined): string {
  if (!value) return '';
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;');
}
